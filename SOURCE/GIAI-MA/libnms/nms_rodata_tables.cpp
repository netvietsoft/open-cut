const NmsRc4Entry* find_rc4_entry_by_ct_vaddr(uint32_t ct_vaddr) noexcept {
    for (const auto& entry : kNmsRc4Catalog) {
        if (entry.ct_vaddr == ct_vaddr) {
            return &entry;
        }
    }
    return nullptr;
}

uint64_t lookup_data_mba_resolved_vaddr(uint32_t data_vaddr) noexcept {
    for (const auto& item : kNmsMetaEntryMbaRelocPair) {
        if (item.data_vaddr == data_vaddr) {
            return item.resolved_vaddr;
        }
    }
    for (const auto& item : kNmsDataMbaRelocTable) {
        if (item.data_vaddr == data_vaddr) {
            return item.resolved_vaddr;
        }
    }
    return 0ULL;
}

