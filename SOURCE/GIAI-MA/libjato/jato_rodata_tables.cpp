// [EN] Binary search lookup for .rodata strings by virtual address
// [VN] Tìm kiếm nhị phân chuỗi .rodata theo địa chỉ ảo
const char* LookupRodataString(uint32_t va) noexcept {
    size_t lo = 0;
    size_t hi = kRodataStringTableCount;
    while (lo < hi) {
        size_t mid = lo + ((hi - lo) >> 1);
        if (kRodataStringTable[mid].va == va) {
            return kRodataStringTable[mid].text;
        }
        if (kRodataStringTable[mid].va < va) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    return "";
}

